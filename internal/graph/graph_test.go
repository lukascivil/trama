func TestReplaceMarkedKeepsOutside(t *testing.T) {
	doc := "# Title\n\nbefore\n<!-- trama:begin -->\nold\n<!-- trama:end -->\nafter\n"
	got, err := graph.ReplaceMarked(doc, "new table")
	if err != nil {
		t.Fatal(err)
	}
	want := "# Title\n\nbefore\n<!-- trama:begin -->\nnew table\n<!-- trama:end -->\nafter\n"
	if got != want {
		t.Fatalf("got %q\nwant %q", got, want)
	}
	for _, bad := range []string{"no markers", "<!-- trama:end -->\n<!-- trama:begin -->\n", "<!-- trama:begin -->\nonly begin"} {
		if _, err := graph.ReplaceMarked(bad, "x"); err == nil {
			t.Errorf("ReplaceMarked(%q) accepted", bad)
		}
	}
}

func TestGraphRefusesWithoutMarkers(t *testing.T) {
	ws := demoWorkspace(t)
	agents := filepath.Join(ws.Root, "AGENTS.md")
	if err := os.WriteFile(agents, []byte("# hand written\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := graph.Write(ws); err == nil || !strings.Contains(err.Error(), "marker") {
		t.Fatalf("err = %v", err)
	}
	if _, err := os.Stat(filepath.Join(ws.Root, "docs", "graph.md")); !os.IsNotExist(err) {
		t.Fatal("docs/graph.md written although AGENTS.md has no markers")
	}
	if b, _ := os.ReadFile(agents); string(b) != "# hand written\n" {
		t.Fatalf("AGENTS.md changed: %q", b)
	}
}
