func demoWorkspace(t *testing.T, extraRepos ...string) *workspace.Workspace {
	t.Helper()
	root := t.TempDir()
	yml := "version: 1\nname: demo\nrepos:\n" +
		"  - {name: trama-demo-api, url: https://github.com/x/api.git, branch: main}\n" +
		"  - {name: trama-demo-web, url: https://github.com/x/web.git, branch: main}\n"
	for _, r := range extraRepos {
		yml += "  - {name: " + r + ", url: https://github.com/x/" + r + ".git, branch: main}\n"
	}
	if err := os.WriteFile(filepath.Join(root, workspace.FileName), []byte(yml), 0o644); err != nil {
		t.Fatal(err)
	}
	ws, err := workspace.Load(root)
	if err != nil {
		t.Fatal(err)
	}
	return ws
}

func demoCards() map[string]*catalog.Card {
	return map[string]*catalog.Card{
		"trama-demo-api": {Name: "trama-demo-api", Stack: []string{"go"},
			Provides: []catalog.Provide{{Kind: "http", ID: "GET /hello"}}},
		"trama-demo-web": {Name: "trama-demo-web", Stack: []string{"node", "react", "typescript"},
			Consumes: []catalog.Consume{{Kind: "http", ID: "GET /hello", From: "trama-demo-api", Via: "env"}}},
	}
}

func TestBuildDemo(t *testing.T) {
	rels, pending := graph.Build(demoWorkspace(t), demoCards())
	want := []graph.Relation{{Consumer: "trama-demo-web", Provider: "trama-demo-api", Kind: "http", ID: "GET /hello", Via: "env"}}
	if !reflect.DeepEqual(rels, want) || len(pending) != 0 {
		t.Fatalf("rels = %+v, pending = %+v", rels, pending)
	}
}

func TestDocDemo(t *testing.T) {
	ws := demoWorkspace(t)
	rels, pending := graph.Build(ws, demoCards())
	doc := graph.Doc(ws, rels, pending)
	for _, want := range []string{
		"# Dependency graph",
		"<!-- Generated by trama graph from catalog/. Do not edit by hand. -->",
		"```mermaid\ngraph LR\n",
		`n0["trama-demo-api"]`,
		`n1["trama-demo-web"]`,
		`n1 -->|"GET /hello"| n0`,
		"| trama-demo-web | trama-demo-api | http | GET /hello | env |",
	} {
		if !strings.Contains(doc, want) {
			t.Errorf("doc lacks %q:\n%s", want, doc)
		}
	}
	if strings.Contains(doc, "## Pending") {
		t.Errorf("doc has a Pending section without pending relations:\n%s", doc)
	}
}

func TestGraphShowsPending(t *testing.T) {
	ws := demoWorkspace(t, "billing")
	cards := demoCards()
	cards["trama-demo-web"].Consumes = append(cards["trama-demo-web"].Consumes,
		catalog.Consume{Kind: "http", ID: "GET /health", From: catalog.Unknown, Candidates: []string{"trama-demo-api", "billing"}})
	rels, pending := graph.Build(ws, cards)
	doc := graph.Doc(ws, rels, pending)
	for _, want := range []string{
		`u1(("?"))`,
		`n1 -.->|"GET /health"| u1`,
		"## Pending",
		"| trama-demo-web | http | GET /health | trama-demo-api, billing |",
		`n2["billing"]`,
	} {
		if !strings.Contains(doc, want) {
			t.Errorf("doc lacks %q:\n%s", want, doc)
		}
	}
}

func TestDocDrawsOneArrowPerPair(t *testing.T) {
	ws := demoWorkspace(t)
	cards := demoCards()
	api := cards["trama-demo-api"]
	web := cards["trama-demo-web"]
	for _, id := range []string{"GET /orders", "POST /orders"} {
		api.Provides = append(api.Provides, catalog.Provide{Kind: "http", ID: id})
		web.Consumes = append(web.Consumes, catalog.Consume{Kind: "http", ID: id, From: "trama-demo-api", Via: "route"})
	}
	rels, pending := graph.Build(ws, cards)
	doc := graph.Doc(ws, rels, pending)
	if !strings.Contains(doc, `n1 -->|"3 relations"| n0`) {
		t.Errorf("the three routes were not drawn as one arrow:\n%s", doc)
	}
	if strings.Contains(doc, `|"GET /orders"| n0`) {
		t.Errorf("a bundled route still has its own arrow:\n%s", doc)
	}
	for _, want := range []string{"| trama-demo-web | trama-demo-api | http | GET /orders | route |", "| trama-demo-web | trama-demo-api | http | GET /hello | env |"} {
		if !strings.Contains(doc, want) {
			t.Errorf("the table lost %q:\n%s", want, doc)
		}
	}
}

