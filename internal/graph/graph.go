// Package graph turns the catalog into docs/graph.md and the generated
// section of AGENTS.md. Same catalog in, same bytes out.
package graph

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/lukascivil/trama/internal/catalog"
	"github.com/lukascivil/trama/internal/workspace"
)

const (
	beginMarker = "<!-- trama:begin -->"
	endMarker   = "<!-- trama:end -->"
)

// Relation is a consume with a proven provider.
type Relation struct{ Consumer, Provider, Kind, ID, Via string }

// Pending is a consume whose provider is not proven yet.
type Pending struct {
	Consumer, Kind, ID string
	Candidates         []string
}

// Build lists relations and pending consumes in workspace order, then card order.
func Build(ws *workspace.Workspace, cards map[string]*catalog.Card) ([]Relation, []Pending) {
	var rels []Relation
	var pending []Pending
	for _, r := range ws.Repos {
		c := cards[r.Name]
		if c == nil {
			continue
		}
		for _, cs := range c.Consumes {
			if cs.From == catalog.Unknown {
				pending = append(pending, Pending{Consumer: r.Name, Kind: cs.Kind, ID: cs.ID, Candidates: cs.Candidates})
				continue
			}
			rels = append(rels, Relation{Consumer: r.Name, Provider: cs.From, Kind: cs.Kind, ID: cs.ID, Via: cs.Via})
		}
	}
	return rels, pending
}

// Doc renders docs/graph.md.
func Doc(ws *workspace.Workspace, rels []Relation, pending []Pending) string {
	node := map[string]string{}
	var b strings.Builder
	b.WriteString("# Dependency graph\n\n<!-- Generated by trama graph from catalog/. Do not edit by hand. -->\n\n")
	b.WriteString("```mermaid\ngraph LR\n")
	for i, r := range ws.Repos {
		node[r.Name] = fmt.Sprintf("n%d", i)
		fmt.Fprintf(&b, "  n%d[\"%s\"]\n", i, mermaidText(r.Name))
	}
	if len(pending) > 0 {
		b.WriteString("  unknown((\"?\"))\n")
	}
	for _, rel := range rels {
		fmt.Fprintf(&b, "  %s -->|\"%s\"| %s\n", node[rel.Consumer], mermaidText(rel.ID), node[rel.Provider])
	}
	for _, p := range pending {
		fmt.Fprintf(&b, "  %s -.->|\"%s\"| unknown\n", node[p.Consumer], mermaidText(p.ID))
	}
	b.WriteString("```\n\n## Relations\n\n")
	if len(rels) == 0 {
		b.WriteString("_No relations yet._\n")
	} else {
		b.WriteString("| Consumer | Provider | Kind | ID | Via |\n|---|---|---|---|---|\n")
		for _, rel := range rels {
			fmt.Fprintf(&b, "| %s | %s | %s | %s | %s |\n", cell(rel.Consumer), cell(rel.Provider), cell(rel.Kind), cell(rel.ID), cell(rel.Via))
		}
	}
	if len(pending) > 0 {
		b.WriteString("\n## Pending\n\n| Consumer | Kind | ID | Candidates |\n|---|---|---|---|\n")
		for _, p := range pending {
			cands := "—"
			if len(p.Candidates) > 0 {
				cands = strings.Join(p.Candidates, ", ")
			}
			fmt.Fprintf(&b, "| %s | %s | %s | %s |\n", cell(p.Consumer), cell(p.Kind), cell(p.ID), cell(cands))
		}
	}
	return b.String()
}

// AgentsSection renders the table that goes between the AGENTS.md markers.
func AgentsSection(ws *workspace.Workspace, cards map[string]*catalog.Card) string {
	var b strings.Builder
	b.WriteString("| Repository | Stack | Provides | Consumes |\n|---|---|---|---|\n")
	for _, r := range ws.Repos {
		c := cards[r.Name]
		if c == nil {
			fmt.Fprintf(&b, "| %s | _not mapped yet_ | — | — |\n", cell(r.Name))
			continue
		}
		var provides, consumes []string
		for _, p := range c.Provides {
			provides = append(provides, p.ID)
		}
		for _, cs := range c.Consumes {
			from := cs.From
			if from == catalog.Unknown {
				from = "?"
			}
			consumes = append(consumes, cs.ID+" ← "+from)
		}
		fmt.Fprintf(&b, "| %s | %s | %s | %s |\n", cell(r.Name), cell(strings.Join(c.Stack, ", ")), cell(orDash(provides)), cell(orDash(consumes)))
	}
	b.WriteString("\nSee [docs/graph.md](docs/graph.md).")
	return b.String()
}

// ReplaceMarked replaces what is between the trama marker lines and keeps
// the rest of doc byte for byte. A marker counts only as a whole line, so
// prose that mentions it is left alone; there must be exactly one of each.
func ReplaceMarked(doc, section string) (string, error) {
	var begins, ends [][2]int // byte offsets of each marker line, without its newline
	off := 0
	for _, line := range strings.SplitAfter(doc, "\n") {
		content := strings.TrimRight(line, "\r\n")
		switch strings.TrimSpace(content) {
		case beginMarker:
			begins = append(begins, [2]int{off, off + len(content)})
		case endMarker:
			ends = append(ends, [2]int{off, off + len(content)})
		}
		off += len(line)
	}
	if len(begins) != 1 || len(ends) != 1 || ends[0][0] < begins[0][1] {
		return "", errors.New("AGENTS.md needs exactly one begin marker line (" + beginMarker + ") and one end marker line (" + endMarker + "), in that order")
	}
	return doc[:begins[0][1]] + "\n" + section + "\n" + doc[ends[0][0]:], nil
}

// Write loads the cards and writes docs/graph.md and the AGENTS.md section.
// It writes nothing when AGENTS.md cannot be updated.
func Write(ws *workspace.Workspace) error {
	cards := map[string]*catalog.Card{}
	for _, r := range ws.Repos {
		c, err := catalog.LoadStrict(ws.Root, r.Name)
		if err != nil {
			return err
		}
		if c != nil {
			cards[r.Name] = c
		}
	}
	agentsPath := filepath.Join(ws.Root, "AGENTS.md")
	agents, err := os.ReadFile(agentsPath)
	if err != nil {
		return err
	}
	updated, err := ReplaceMarked(string(agents), AgentsSection(ws, cards))
	if err != nil {
		return err
	}
	rels, pending := Build(ws, cards)
	docs := filepath.Join(ws.Root, "docs")
	if fi, err := os.Lstat(docs); err == nil && !fi.IsDir() {
		return errors.New("docs is not a directory (a symbolic link?): refusing to write outside the workspace")
	}
	if err := os.MkdirAll(docs, 0o755); err != nil {
		return err
	}
	if err := replaceFile(filepath.Join(docs, "graph.md"), []byte(Doc(ws, rels, pending))); err != nil {
		return err
	}
	return replaceFile(agentsPath, []byte(updated))
}

// replaceFile writes data to a new file next to path and renames it over
// path, so a symbolic link at path is replaced instead of followed.
func replaceFile(path string, data []byte) error {
	tmp, err := os.CreateTemp(filepath.Dir(path), ".trama-*")
	if err != nil {
		return err
	}
	defer os.Remove(tmp.Name())
	if _, err := tmp.Write(data); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Chmod(0o644); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	return os.Rename(tmp.Name(), path)
}

func orDash(items []string) string {
	if len(items) == 0 {
		return "—"
	}
	return strings.Join(items, ", ")
}

func cell(s string) string {
	return strings.ReplaceAll(s, "|", `\|`)
}

func mermaidText(s string) string {
	return strings.ReplaceAll(s, `"`, "#quot;")
}
